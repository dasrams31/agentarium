  function currentLang() {
    try {
      var saved = window.localStorage.getItem(LANG_KEY);
      if (saved === 'id' || saved === 'en') return saved;
    } catch (e) { /* abaikan: pakai default */ }
    return 'en'; /* default: English */
  }

  function stringsFor(lang) {
    return STRINGS[lang] || STRINGS.en;
  }

  /* Terjemahkan key; fallback ke key itu sendiri bila belum ada. */
  function t(key) {
    var s = stringsFor(currentLang());
    return (s[key] !== undefined) ? s[key] : key;
  }

  function applyLang(lang) {
    var strings = stringsFor(lang);
    document.documentElement.setAttribute('lang', lang);

    var els = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < els.length; i++) {
      var key = els[i].getAttribute('data-i18n');
      if (strings[key] !== undefined) els[i].textContent = strings[key];
    }

    var aels = document.querySelectorAll('[data-i18n-attr]');
    for (var j = 0; j < aels.length; j++) {
      var specs = String(aels[j].getAttribute('data-i18n-attr')).split(';');
      for (var k = 0; k < specs.length; k++) {
        var idx = specs[k].indexOf(':');
        if (idx < 1) continue;
        var attr = specs[k].slice(0, idx).trim();
        var akey = specs[k].slice(idx + 1).trim();
        if (attr && strings[akey] !== undefined) {
          aels[j].setAttribute(attr, strings[akey]);
        }
      }
    }

    var btns = document.querySelectorAll('[data-lang-btn]');
    for (var m = 0; m < btns.length; m++) {
      var active = btns[m].getAttribute('data-lang-btn') === lang;
      if (btns[m].classList) btns[m].classList.toggle('active', active);
      btns[m].setAttribute('aria-pressed', active ? 'true' : 'false');
    }
  }

  function setLang(lang) {
    if (lang !== 'id' && lang !== 'en') return;
    try { window.localStorage.setItem(LANG_KEY, lang); } catch (e) { /* abaikan */ }
    applyLang(lang);
  }

  function initI18n() {
    var btns = document.querySelectorAll('[data-lang-btn]');
    for (var i = 0; i < btns.length; i++) {
      (function (btn) {
        btn.addEventListener('click', function () {
          setLang(btn.getAttribute('data-lang-btn'));
        });
      })(btns[i]);
    }
    applyLang(currentLang());
  }

  window.AgentariumI18n = {
    setLang: setLang,
    init: initI18n,
    apply: applyLang,
    t: t,
    current: currentLang
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initI18n);
  } else {
    initI18n();
  }
